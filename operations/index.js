import { resolveLocalRef } from '../openapi/index.js';

const HTTP_METHODS=['get','put','post','delete','options','head','patch','trace'];

export function collectApiOperations(openapi){
  if(!openapi||typeof openapi!=='object')throw new Error('An OpenAPI document is required.');
  const operations=[];const seen=new Set();
  for(const [operationPath,unresolvedPathItem] of Object.entries(openapi.paths||{})){
    const pathItem=resolveLocalRef(openapi,unresolvedPathItem)||{};
    const inherited=resolveParameters(openapi,pathItem.parameters||[]);
    for(const method of HTTP_METHODS){
      if(!pathItem[method])continue;
      const operation=resolveLocalRef(openapi,pathItem[method])||{};
      const operationId=operation.operationId;
      if(!operationId)throw new Error(`${method.toUpperCase()} ${operationPath} is missing operationId.`);
      if(seen.has(operationId))throw new Error(`Duplicate OpenAPI operationId: ${operationId}`);
      seen.add(operationId);
      const parameters=mergeParameters(inherited,resolveParameters(openapi,operation.parameters||[]));
      const requestBody=operation.requestBody?resolveLocalRef(openapi,operation.requestBody):null;
      const requestContent=requestBody?.content||{};
      const responseSchema=resolveResponseSchema(openapi,operation.responses||{});
      operations.push({
        operationId,
        projectId:operation['x-project-id']||null,
        method:method.toUpperCase(),
        path:operationPath,
        parameters:parameters.map(parameter=>({name:parameter.name,in:parameter.in,required:Boolean(parameter.required||parameter.in==='path'),schema:resolveSchema(openapi,parameter.schema)})),
        requestBody:requestBody?{required:Boolean(requestBody.required),contentTypes:Object.keys(requestContent),schema:resolveContentSchema(openapi,requestContent)}:null,
        responseSchema
      });
    }
  }
  return operations;
}

export function generateApiModule({openapi,apiRoot=''}={}){
  const operations=collectApiOperations(openapi);
  const table=Object.fromEntries(operations.map(operation=>[operation.operationId,operation]));
  return `// Generated by Metaproject. Do not edit manually.\n`+`export const DEFAULT_API_ROOT = ${JSON.stringify(String(apiRoot??''))};\n`+`export const OPERATIONS = deepFreeze(${JSON.stringify(table,null,2)});\n\n`+`function deepFreeze(value){if(!value||typeof value!=='object'||Object.isFrozen(value))return value;Object.freeze(value);for(const child of Object.values(value))deepFreeze(child);return value;}\n`;
}

function resolveParameters(openapi,parameters){return(parameters||[]).map(parameter=>resolveLocalRef(openapi,parameter));}
function mergeParameters(inherited,own){const merged=new Map();for(const parameter of [...(inherited||[]),...(own||[])]){if(!parameter?.name||!parameter?.in)continue;merged.set(`${parameter.in}:${parameter.name}`,parameter);}return[...merged.values()];}
function resolveSchema(openapi,schema){if(!schema)return null;return resolveLocalRef(openapi,schema)||schema;}
function resolveContentSchema(openapi,content){const media=content?.['application/json']||content?.['application/problem+json']||Object.values(content||{})[0];return resolveSchema(openapi,media?.schema);}
function resolveResponseSchema(openapi,responses){const entries=Object.entries(responses||{}).filter(([status])=>/^2\d\d$/.test(status)||status==='default');entries.sort(([a],[b])=>a==='default'?1:b==='default'?-1:Number(a)-Number(b));for(const [,unresolved] of entries){const response=resolveLocalRef(openapi,unresolved)||{};const schema=resolveContentSchema(openapi,response.content||{});if(schema)return schema;}return null;}
