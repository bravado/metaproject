import { resolveLocalRef } from '../openapi/index.js';

const HTTP_METHODS = ['get', 'put', 'post', 'delete', 'options', 'head', 'patch', 'trace'];

/**
 * Convert an OpenAPI document into the small operation table needed by the
 * production browser API client. OpenAPI server URLs are deliberately ignored:
 * Metaproject's application contract is api_root + operation path.
 */
export function collectApiOperations(openapi) {
  if (!openapi || typeof openapi !== 'object') throw new Error('An OpenAPI document is required.');
  const operations = [];
  const seen = new Set();

  for (const [operationPath, unresolvedPathItem] of Object.entries(openapi.paths || {})) {
    const pathItem = resolveLocalRef(openapi, unresolvedPathItem) || {};
    const inheritedParameters = resolveParameters(openapi, pathItem.parameters || []);

    for (const method of HTTP_METHODS) {
      if (!pathItem[method]) continue;
      const operation = resolveLocalRef(openapi, pathItem[method]) || {};
      const operationId = operation.operationId;
      if (!operationId) throw new Error(`${method.toUpperCase()} ${operationPath} is missing operationId.`);
      if (seen.has(operationId)) throw new Error(`Duplicate OpenAPI operationId: ${operationId}`);
      seen.add(operationId);

      const ownParameters = resolveParameters(openapi, operation.parameters || []);
      const parameters = mergeParameters(inheritedParameters, ownParameters);
      const requestBody = operation.requestBody ? resolveLocalRef(openapi, operation.requestBody) : null;
      const contentTypes = Object.keys(requestBody?.content || {});

      operations.push({
        operationId,
        projectId: operation['x-project-id'] || null,
        method: method.toUpperCase(),
        path: operationPath,
        parameters: parameters.map(parameter => ({
          name: parameter.name,
          in: parameter.in,
          required: Boolean(parameter.required || parameter.in === 'path')
        })),
        requestBody: requestBody ? {
          required: Boolean(requestBody.required),
          contentTypes
        } : null
      });
    }
  }

  return operations;
}

/**
 * Generate a self-contained browser ESM client. The output intentionally has
 * no bare imports so it can live directly under public/components/api.js in a
 * PHP application and be served as a static asset.
 */
export function generateApiClientModule({ openapi, apiRoot = '' } = {}) {
  const operations = collectApiOperations(openapi);
  const operationTable = Object.fromEntries(operations.map(operation => [operation.operationId, operation]));
  const methods = operations.map(operation => {
    return `    ${JSON.stringify(operation.operationId)}: (args = {}) => invoke(OPERATIONS[${JSON.stringify(operation.operationId)}], args)`;
  }).join(',\n');

  return `// Generated by Metaproject. Do not edit manually.\n` +
`export const DEFAULT_API_ROOT = ${JSON.stringify(String(apiRoot ?? ''))};\n` +
`export const OPERATIONS = deepFreeze(${JSON.stringify(operationTable, null, 2)});\n\n` +
`export class ApiClientError extends Error {\n` +
`  constructor(message, { operationId, status, response, body } = {}) {\n` +
`    super(message);\n` +
`    this.name = 'ApiClientError';\n` +
`    this.operationId = operationId;\n` +
`    this.status = status;\n` +
`    this.response = response;\n` +
`    this.body = body;\n` +
`  }\n` +
`}\n\n` +
`export function createApiClient(options = {}) {\n` +
`  const apiRoot = options.apiRoot ?? DEFAULT_API_ROOT;\n` +
`  const fetchImpl = options.fetch ?? globalThis.fetch?.bind(globalThis);\n` +
`  const defaultHeaders = { ...(options.headers || {}) };\n` +
`  const defaultCredentials = options.credentials ?? 'same-origin';\n\n` +
`  const invoke = async (operation, args = {}) => {\n` +
`    if (typeof fetchImpl !== 'function') throw new Error('No fetch implementation is available for the Metaproject API client.');\n` +
`    const pathValues = args.path || {};\n` +
`    const queryValues = args.query || {};\n` +
`    const callHeaders = { ...defaultHeaders, ...(args.headers || {}) };\n` +
`    validateRequiredParameters(operation, { path:pathValues, query:queryValues, headers:callHeaders });\n` +
`    if (operation.requestBody?.required && args.body === undefined) throw new Error(operation.operationId + ': request body is required.');\n\n` +
`    const expandedPath = expandPath(operation.path, pathValues, operation.operationId);\n` +
`    const url = appendQuery(joinApiUrl(apiRoot, expandedPath), queryValues);\n` +
`    const init = {\n` +
`      ...(args.request || {}),\n` +
`      method: operation.method,\n` +
`      headers: callHeaders,\n` +
`      credentials: args.request?.credentials ?? defaultCredentials\n` +
`    };\n` +
`    if (args.signal !== undefined) init.signal = args.signal;\n` +
`    if (args.body !== undefined) init.body = prepareBody(args.body, operation.requestBody?.contentTypes || [], callHeaders);\n\n` +
`    const response = await fetchImpl(url, init);\n` +
`    const body = await readResponseBody(response);\n` +
`    if (!response.ok) {\n` +
`      throw new ApiClientError(operation.operationId + ' failed with HTTP ' + response.status, {\n` +
`        operationId:operation.operationId, status:response.status, response, body\n` +
`      });\n` +
`    }\n` +
`    return body;\n` +
`  };\n\n` +
`  return Object.freeze({\n${methods}\n` +
`  });\n` +
`}\n\n` +
`export const api = createApiClient();\n` +
`export default api;\n\n` +
`export function joinApiUrl(apiRoot, operationPath) {\n` +
`  const root = String(apiRoot ?? '').replace(/\\/+$/, '');\n` +
`  const path = String(operationPath || '').startsWith('/') ? String(operationPath || '') : '/' + String(operationPath || '');\n` +
`  if (!root || root === '/') return path || '/';\n` +
`  return root + path;\n` +
`}\n\n` +
`function expandPath(template, values, operationId) {\n` +
`  return String(template).replace(/\\{([^}]+)\\}/g, (_match, name) => {\n` +
`    const value = values[name];\n` +
`    if (value === undefined || value === null) throw new Error(operationId + ': missing required path parameter ' + name + '.');\n` +
`    return encodeURIComponent(String(value));\n` +
`  });\n` +
`}\n\n` +
`function appendQuery(url, query) {\n` +
`  const params = new URLSearchParams();\n` +
`  for (const [name, raw] of Object.entries(query || {})) {\n` +
`    if (raw === undefined || raw === null) continue;\n` +
`    if (Array.isArray(raw)) { for (const value of raw) if (value !== undefined && value !== null) params.append(name, String(value)); }\n` +
`    else params.append(name, String(raw));\n` +
`  }\n` +
`  const suffix = params.toString();\n` +
`  if (!suffix) return url;\n` +
`  return url + (url.includes('?') ? '&' : '?') + suffix;\n` +
`}\n\n` +
`function validateRequiredParameters(operation, values) {\n` +
`  for (const parameter of operation.parameters || []) {\n` +
`    if (!parameter.required) continue;\n` +
`    if (parameter.in === 'path' || parameter.in === 'query') {\n` +
`      const value = values[parameter.in]?.[parameter.name];\n` +
`      if (value === undefined || value === null) throw new Error(operation.operationId + ': missing required ' + parameter.in + ' parameter ' + parameter.name + '.');\n` +
`    } else if (parameter.in === 'header' && !hasHeader(values.headers, parameter.name)) {\n` +
`      throw new Error(operation.operationId + ': missing required header parameter ' + parameter.name + '.');\n` +
`    }\n` +
`  }\n` +
`}\n\n` +
`function prepareBody(body, contentTypes, headers) {\n` +
`  if (isNativeBody(body)) return body;\n` +
`  const contentType = preferredContentType(contentTypes);\n` +
`  if (contentType && !hasHeader(headers, 'content-type')) setHeader(headers, 'Content-Type', contentType);\n` +
`  if (!contentType || /(^|\\+)json(?:$|;|\\+)/i.test(contentType) || /\\/json(?:$|;)/i.test(contentType)) return JSON.stringify(body);\n` +
`  if (contentType === 'application/x-www-form-urlencoded' && body && typeof body === 'object') return new URLSearchParams(body);\n` +
`  return body;\n` +
`}\n\n` +
`function preferredContentType(contentTypes) {\n` +
`  if (!contentTypes?.length) return 'application/json';\n` +
`  return contentTypes.find(value => /json/i.test(value)) || contentTypes[0];\n` +
`}\n\n` +
`function isNativeBody(value) {\n` +
`  if (typeof value === 'string') return true;\n` +
`  if (typeof Blob !== 'undefined' && value instanceof Blob) return true;\n` +
`  if (typeof FormData !== 'undefined' && value instanceof FormData) return true;\n` +
`  if (typeof URLSearchParams !== 'undefined' && value instanceof URLSearchParams) return true;\n` +
`  if (typeof ArrayBuffer !== 'undefined' && (value instanceof ArrayBuffer || ArrayBuffer.isView?.(value))) return true;\n` +
`  return false;\n` +
`}\n\n` +
`async function readResponseBody(response) {\n` +
`  if (response.status === 204 || response.status === 205) return undefined;\n` +
`  const contentType = response.headers?.get?.('content-type') || '';\n` +
`  if (/json/i.test(contentType)) {\n` +
`    try { return await response.json(); } catch { return undefined; }\n` +
`  }\n` +
`  const text = await response.text();\n` +
`  return text === '' ? undefined : text;\n` +
`}\n\n` +
`function hasHeader(headers, name) {\n` +
`  const target = String(name).toLowerCase();\n` +
`  return Object.keys(headers || {}).some(key => key.toLowerCase() === target);\n` +
`}\n` +
`function setHeader(headers, name, value) {\n` +
`  const target = String(name).toLowerCase();\n` +
`  const existing = Object.keys(headers).find(key => key.toLowerCase() === target);\n` +
`  headers[existing || name] = value;\n` +
`}\n` +
`function deepFreeze(value) {\n` +
`  if (!value || typeof value !== 'object' || Object.isFrozen(value)) return value;\n` +
`  Object.freeze(value);\n` +
`  for (const child of Object.values(value)) deepFreeze(child);\n` +
`  return value;\n` +
`}\n`;
}

function resolveParameters(openapi, parameters) {
  return (parameters || []).map(parameter => resolveLocalRef(openapi, parameter));
}

function mergeParameters(inherited, own) {
  const merged = new Map();
  for (const parameter of [...(inherited || []), ...(own || [])]) {
    if (!parameter?.name || !parameter?.in) continue;
    merged.set(`${parameter.in}:${parameter.name}`, parameter);
  }
  return [...merged.values()];
}
